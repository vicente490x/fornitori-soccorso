-- Solo demo: sessioni Telegram e risposte persistenti per webhook stateless.
-- Migrazione additiva: non modificare altri progetti/database.
BEGIN;
CREATE TABLE IF NOT EXISTS telegram_conversations (
 chat_id VARCHAR(120) PRIMARY KEY,
 session_id VARCHAR(64) NOT NULL,
 stage VARCHAR(24) NOT NULL DEFAULT 'START',
 plate VARCHAR(20),
 phone VARCHAR(24),
 customer_id BIGINT,
 origin_address VARCHAR(500),
 latitude NUMERIC(17,12),
 longitude NUMERIC(17,12),
 request_id VARCHAR(64),
 last_update_id BIGINT NOT NULL DEFAULT -1,
 failures INTEGER NOT NULL DEFAULT 0,
 touched_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS telegram_outbound (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id VARCHAR(120) NOT NULL,
 update_id BIGINT NOT NULL,
 sequence_number INTEGER NOT NULL,
 body TEXT NOT NULL,
 problem_buttons BOOLEAN NOT NULL DEFAULT FALSE,
 sent_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(chat_id, update_id, sequence_number)
);
CREATE INDEX IF NOT EXISTS ix_telegram_outbound_unsent ON telegram_outbound(chat_id, id) WHERE sent_at IS NULL;
-- Il ruolo del deploy riceve solo le autorizzazioni necessarie. Sostituire il nome
-- se il runtime Neon usa un ruolo diverso.
GRANT SELECT, INSERT, UPDATE, DELETE ON telegram_conversations, telegram_outbound TO fornitori_app;
GRANT USAGE, SELECT ON SEQUENCE telegram_outbound_id_seq TO fornitori_app;
COMMIT;
